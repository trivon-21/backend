const FORWARD_TRANSITIONS = Object.freeze({
  'to-pack': 'ready',
  ready: 'in-transit',
  'in-transit': 'completed',
});
const REVERSE_TRANSITIONS = Object.freeze({
  ready: 'to-pack',
  'in-transit': 'ready',
  completed: 'in-transit',
});
const UNDO_WINDOW_MS = 60 * 60 * 1000;

function workflowError(message, statusCode, code) {
  const error = new Error(message);
  error.statusCode = statusCode;
  error.code = code;
  return error;
}

function hasOwn(value, key) {
  return Object.prototype.hasOwnProperty.call(value, key);
}

function assertDispatchVersion(order, suppliedVersion) {
  if (!Number.isInteger(suppliedVersion)
    || suppliedVersion !== Number(order.statusVersion || 0)) {
    throw workflowError('This dispatch changed; refresh before trying again', 409, 'STALE_DISPATCH');
  }
}

function immutablePackingLines(currentItems, proposedItems) {
  if (!Array.isArray(proposedItems) || proposedItems.length !== currentItems.length) {
    throw workflowError('Dispatch line identities and quantities cannot be changed', 409, 'DISPATCH_ITEMS_IMMUTABLE');
  }
  return proposedItems.map((proposed, index) => {
    const current = currentItems[index];
    if (!current || proposed.sku !== current.sku || proposed.name !== current.name
      || Number(proposed.qty) !== Number(current.qty)) {
      throw workflowError('Dispatch line identities and quantities cannot be changed', 409, 'DISPATCH_ITEMS_IMMUTABLE');
    }
    return { ...current, confirmed: Boolean(proposed.confirmed) };
  });
}

function requireShipping(courier, trackId) {
  if (!courier || !trackId) {
    throw workflowError('Courier and tracking ID are required', 400, 'DISPATCH_SHIPPING_REQUIRED');
  }
}

function requireConfirmed(items) {
  if (!items.length || !items.every((item) => item.confirmed)) {
    throw workflowError('Every dispatch item must be confirmed before it can move forward', 409, 'DISPATCH_ITEMS_NOT_CONFIRMED');
  }
}

function assertUndoWindow(order, now) {
  const movedAt = new Date(order.lastMovedAt).getTime();
  const age = now.getTime() - movedAt;
  if (!Number.isFinite(movedAt) || age < 0 || age > UNDO_WINDOW_MS) {
    throw workflowError('The one-hour dispatch undo window has expired', 409, 'DISPATCH_UNDO_EXPIRED');
  }
}

function buildDispatchMutation(order, input = {}, now = new Date()) {
  assertDispatchVersion(order, input.statusVersion);
  if (hasOwn(input, 'lastMovedAt') || hasOwn(input, 'completedAt')) {
    throw workflowError('Dispatch timestamps are generated by the server', 400, 'SERVER_MANAGED_DISPATCH_TIMESTAMP');
  }

  const currentStatus = order.status;
  const nextStatus = input.status || currentStatus;
  const set = {};
  const unset = {};
  let effectiveItems = (order.items || []).map((item) => ({ ...item }));
  const hasItems = hasOwn(input, 'items');
  const hasShipping = hasOwn(input, 'courier') || hasOwn(input, 'trackId');

  if (hasItems) {
    if (currentStatus !== 'to-pack') {
      throw workflowError('Packing confirmation is only editable while the order is to pack', 409, 'DISPATCH_EDIT_NOT_ALLOWED');
    }
    effectiveItems = immutablePackingLines(effectiveItems, input.items);
    set.items = effectiveItems;
  }

  const courier = String(hasOwn(input, 'courier') ? input.courier : order.courier || '').trim();
  const trackId = String(hasOwn(input, 'trackId') ? input.trackId : order.trackId || '').trim();
  if (hasShipping) {
    if (!['to-pack', 'ready'].includes(currentStatus)) {
      throw workflowError('Shipping details cannot be edited at this dispatch stage', 409, 'DISPATCH_EDIT_NOT_ALLOWED');
    }
    requireShipping(courier, trackId);
    set.courier = courier;
    set.trackId = trackId;
  }

  const transitioned = nextStatus !== currentStatus;
  if (transitioned) {
    if (input.undo === true) {
      if (REVERSE_TRANSITIONS[currentStatus] !== nextStatus) {
        throw workflowError('Only the immediately previous dispatch stage can be restored', 409, 'INVALID_DISPATCH_TRANSITION');
      }
      assertUndoWindow(order, now);
      if (currentStatus === 'completed') unset.completedAt = 1;
    } else {
      if (FORWARD_TRANSITIONS[currentStatus] !== nextStatus) {
        throw workflowError('Dispatch stages must move forward one step at a time', 409, 'INVALID_DISPATCH_TRANSITION');
      }
      requireConfirmed(effectiveItems);
      requireShipping(courier, trackId);
      if (nextStatus === 'completed') set.completedAt = now;
    }
    set.status = nextStatus;
    set.lastMovedAt = now;
  } else if (input.undo === true) {
    throw workflowError('Undo requires the immediately previous dispatch status', 409, 'INVALID_DISPATCH_TRANSITION');
  }

  if (!transitioned && !hasItems && !hasShipping) {
    throw workflowError('No supported dispatch change was supplied', 400, 'EMPTY_DISPATCH_UPDATE');
  }

  return { set, unset, transitioned, previousStatus: currentStatus, nextStatus };
}

module.exports = {
  FORWARD_TRANSITIONS,
  REVERSE_TRANSITIONS,
  UNDO_WINDOW_MS,
  assertDispatchVersion,
  buildDispatchMutation,
};
